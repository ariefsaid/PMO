-- The link is written only by the report call, and a tool task is set Done only by the close call (FR-CTR-014):
-- a direct Done while its report is open is refused, so a report is never left open behind a Done task.
create function public.guard_crew_tool_task() returns trigger
  language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if coalesce(current_setting('pmo.crew_tool_rpc', true), '') = 'on' then return new; end if;
  if tg_op = 'INSERT' then
    if new.crew_tool_report_id is not null then
      raise exception 'CTR_TASK_LINK: a tool task is created by the report call only' using errcode = '42501';
    end if;
    return new;
  end if;
  if new.crew_tool_report_id is distinct from old.crew_tool_report_id then
    raise exception 'CTR_TASK_LINK: a tool task cannot be re-linked' using errcode = '42501';
  end if;
  if new.crew_tool_report_id is not null and new.status = 'Done' and old.status is distinct from 'Done'
     and exists (select 1 from public.crew_tool_reports r where r.id = new.crew_tool_report_id and r.status = 'open') then
    raise exception 'CTR_RESOLVE_REQUIRED: choose a resolution (replaced, repaired or written off) to close this tool report'
      using errcode = '23514';
  end if;
  return new;
end $$;
revoke all on function public.guard_crew_tool_task() from public, anon, authenticated;
create trigger tasks_zz_crew_tool_guard before insert or update on public.tasks
  for each row execute function public.guard_crew_tool_task();
