-- The 0036 parent-stamp pattern: the file's organisation is its report's, whatever the client says.
create function public.stamp_crew_tool_file_org() returns trigger
  language plpgsql security definer set search_path = public, pg_temp as $$
declare v_org uuid;
begin
  select r.org_id into v_org from public.crew_tool_reports r where r.id = new.report_id;
  if v_org is null then
    raise exception 'CTR_REF: the report does not exist' using errcode = '23503';
  end if;
  new.org_id := v_org;
  return new;
end $$;
revoke all on function public.stamp_crew_tool_file_org() from public, anon, authenticated;
create trigger crew_tool_report_files_stamp_org_id before insert on public.crew_tool_report_files
  for each row execute function public.stamp_crew_tool_file_org();

-- ── who may report: a crew manager, or the field controller of the line's crew (FR-CTR-016) ─────────────────────────
create function public.crew_tool_can_report(p_line uuid) returns boolean
  language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(public.is_active_member() and exists (
    select 1 from public.crew_tool_lines l join public.crews c on c.id = l.crew_id
     where l.id = p_line and l.org_id = public.auth_org_id()
       and (public.crew_can_manage() or c.field_controller_id = auth.uid())), false)
$$;
revoke all on function public.crew_tool_can_report(uuid) from public, anon;
grant execute on function public.crew_tool_can_report(uuid) to authenticated;

-- The storage object is uploaded before its report exists, so the write policy cannot name the report: it checks
-- the caller's role only (a crew manager or the field controller of some crew) and the report call binds the path.
create function public.crew_tool_is_reporter() returns boolean
  language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(public.is_active_member() and (public.crew_can_manage() or exists (
    select 1 from public.crews c where c.org_id = public.auth_org_id() and c.field_controller_id = auth.uid())), false)
$$;
revoke all on function public.crew_tool_is_reporter() from public, anon;
grant execute on function public.crew_tool_is_reporter() to authenticated;

-- A photo row is evidence only while its uploaded object exists in the bucket.
