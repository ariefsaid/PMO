-- ── the report (FR-CTR-006..010, 015) ───────────────────────────────────────────────────────────────────────────
-- `id` is generated by the client before the call and is the idempotency key (a retry returns the same report,
-- FR-CTR-009) and the photo path's report segment (OD-CTR-5).
create table public.crew_tool_reports (
  id          uuid primary key,
  org_id      uuid not null default coalesce(public.auth_org_id(), '00000000-0000-0000-0000-000000000001')
                references public.organizations(id) on delete cascade,
  line_id     uuid not null references public.crew_tool_lines(id) on delete restrict,
  kind        text not null check (kind in ('damaged', 'lost')),
  qty         integer not null check (qty >= 1),
  note        text check (note is null or char_length(note) <= 500),
  status      text not null default 'open' check (status in ('open', 'closed')),
  resolution  text check (resolution is null or resolution in ('replaced', 'repaired', 'written_off')),
  task_id     uuid references public.tasks(id) on delete set null,
  reported_by uuid references public.profiles(id) default auth.uid(),
  reported_on date not null,
  due_on      date not null,
  closed_by   uuid references public.profiles(id),
  closed_at   timestamptz,
  created_at  timestamptz not null default now(),
  constraint crew_tool_reports_closed check ((status = 'closed') = (resolution is not null and closed_at is not null)),
  constraint crew_tool_reports_repaired_damaged check (resolution is distinct from 'repaired' or kind = 'damaged')
);
create index crew_tool_reports_line_open on public.crew_tool_reports (line_id) where status = 'open';
create index crew_tool_reports_line_idx on public.crew_tool_reports (line_id, created_at desc);
create index crew_tool_reports_org_open on public.crew_tool_reports (org_id, due_on) where status = 'open';
create index crew_tool_reports_task_idx on public.crew_tool_reports (task_id) where task_id is not null;
create index crew_tool_reports_reported_by_idx on public.crew_tool_reports (reported_by) where reported_by is not null;
create index crew_tool_reports_closed_by_idx on public.crew_tool_reports (closed_by) where closed_by is not null;
create trigger crew_tool_reports_stamp_org_id before insert on public.crew_tool_reports
  for each row execute function public.stamp_org_id();

