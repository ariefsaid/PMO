-- ── guards on lines: no archive / move / shrink below the open reports ────────────────────────────────────────────
create function public.guard_crew_tool_line_open_reports() returns trigger
  language plpgsql security definer set search_path = public, pg_temp as $$
declare v_open integer;
begin
  select coalesce(sum(r.qty), 0) into v_open from public.crew_tool_reports r where r.line_id = new.id and r.status = 'open';
  if v_open = 0 then return new; end if;
  if (new.archived_at is not null and old.archived_at is null) or new.crew_id is distinct from old.crew_id then
    raise exception 'CTR_LINE_OPEN_REPORTS: close this line''s open reports first' using errcode = '23514';
  end if;
  if new.held_qty is distinct from old.held_qty and new.held_qty < v_open then
    raise exception 'CTR_QTY: the held quantity cannot go below the % in open reports', v_open using errcode = '23514';
  end if;
  return new;
end $$;
revoke all on function public.guard_crew_tool_line_open_reports() from public, anon, authenticated;
create trigger zz_crew_tool_lines_open_reports before update on public.crew_tool_lines
  for each row execute function public.guard_crew_tool_line_open_reports();

