#!/usr/bin/env node
/**
 * anon-definer-inventory — fragment reader for the client-callable SECURITY DEFINER inventory (#2589).
 *
 * `supabase/tests/0178_anon_executable_definers.test.sql` needs the list of function names a client is
 * allowed to call directly. That list used to be one array in the test file, so every database PR that
 * added a function edited the same lines and the open PRs conflicted on each merge. It is now a
 * directory of fragments, one `.txt` per migration or feature:
 *
 *   supabase/tests/inventory/anon-executable-definers/<feature>.txt     one proname per line, `#` comments
 *
 * pgTAP cannot glob a directory, so this script unions the fragments into one gitignored include
 * (`0178_anon_executable_definers.generated.inc`, beside the test so `\ir` resolves it) that the test includes. The include is never
 * committed (a committed union would conflict exactly like the old array); CI and local runs regenerate it
 * before `supabase test db`. The guarantees are unchanged: an unlisted writer still fails the test's sweep,
 * a stale name still fails its function-exists count (now derived from the union, not hand-kept).
 *
 * Usage:  node scripts/anon-definer-inventory.mjs            validate + (re)write the include
 *         node scripts/anon-definer-inventory.mjs --check    validate only (check:guards; writes nothing)
 *         node scripts/anon-definer-inventory.mjs --self-test
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FRAGMENT_DIR = path.join(ROOT, 'supabase', 'tests', 'inventory', 'anon-executable-definers');
export const OUTPUT_PATH = path.join(ROOT, 'supabase', 'tests', '0178_anon_executable_definers.generated.inc');
const NAME = /^[a-z_][a-z0-9_]*$/;

/** Parse one fragment's text into names. Throws on a malformed line. */
export function parseFragment(text, label) {
  const names = [];
  text.split('\n').forEach((raw, i) => {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) return;
    if (!NAME.test(line)) throw new Error(`${label}:${i + 1}: malformed entry ${JSON.stringify(line)} (one lowercase function name per line)`);
    names.push(line);
  });
  return names;
}

/** Union all fragments; fails on a malformed line, a duplicate anywhere, or an empty directory. */
export function readInventory(dir = FRAGMENT_DIR) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort();
  if (!files.length) throw new Error(`no fragments in ${dir}`);
  const owner = new Map();
  for (const f of files) {
    for (const name of parseFragment(fs.readFileSync(path.join(dir, f), 'utf8'), f)) {
      if (owner.has(name)) throw new Error(`duplicate entry ${name} in ${f} (already in ${owner.get(name)})`);
      owner.set(name, f);
    }
  }
  return [...owner.keys()].sort();
}

export function renderInclude(names) {
  const rows = names.map((n) => `  ('${n}')`).join(',\n');
  return `-- GENERATED by scripts/anon-definer-inventory.mjs from inventory/anon-executable-definers/*.txt — never commit (#2589).\ninsert into client_callable_rpc_names (proname) values\n${rows};\n`;
}

function selfTest() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'anon-inv-'));
  const expectThrow = (label, re, fn) => {
    try { fn(); } catch (err) { if (re.test(err.message)) { console.log(`✓ self-test caught ${label}: ${err.message}`); return; } throw new Error(`self-test: ${label} threw the wrong error: ${err.message}`, { cause: err }); }
    throw new Error(`self-test: ${label} NOT caught`);
  };
  try {
    fs.writeFileSync(path.join(dir, 'a.txt'), '# feature a\nzeta_fn  # note\nalpha_fn\n');
    fs.writeFileSync(path.join(dir, 'b.txt'), 'beta_fn\n\n');
    const union = readInventory(dir);
    if (JSON.stringify(union) !== JSON.stringify(['alpha_fn', 'beta_fn', 'zeta_fn'])) throw new Error(`self-test: union mismatch ${JSON.stringify(union)}`);
    if (!renderInclude(union).includes("('alpha_fn'),\n  ('beta_fn'),\n  ('zeta_fn');")) throw new Error('self-test: rendered include mismatch');
    console.log('✓ self-test: union of two fragments equals the expected sorted set');
    fs.writeFileSync(path.join(dir, 'c.txt'), 'beta_fn\n');
    expectThrow('duplicate across fragments', /duplicate entry beta_fn in c\.txt \(already in b\.txt\)/, () => readInventory(dir));
    fs.writeFileSync(path.join(dir, 'c.txt'), 'Bad-Name()\n');
    expectThrow('malformed fragment', /malformed entry/, () => readInventory(dir));
    fs.rmSync(path.join(dir, 'c.txt'));
    fs.writeFileSync(path.join(dir, 'd.txt'), 'dup_fn\ndup_fn\n');
    expectThrow('duplicate within a fragment', /duplicate entry dup_fn/, () => readInventory(dir));
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir);
    expectThrow('empty fragment directory', /no fragments/, () => readInventory(dir));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  readInventory(); // the shipped fragments must themselves be valid
  console.log('✓ self-test: shipped fragments are valid');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const arg = process.argv[2];
  try {
    if (arg === '--self-test') selfTest();
    else if (arg === '--check') console.log(`PASS anon-definer inventory: ${readInventory().length} names`);
    else if (arg === undefined) {
      const names = readInventory();
      fs.writeFileSync(OUTPUT_PATH, renderInclude(names));
      console.log(`wrote ${path.relative(ROOT, OUTPUT_PATH)}: ${names.length} names`);
    } else { console.error('usage: anon-definer-inventory.mjs [--check | --self-test]'); process.exit(2); }
  } catch (err) { console.error(`✗ ${err.message}`); process.exit(1); }
}
